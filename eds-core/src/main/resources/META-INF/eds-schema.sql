-- =============================================================================
-- Create Script for EDS
-- -----------------------------------------------------------------------------
-- This is the only schema definition for EDS, shared by all supported
-- databases (PostgreSQL and H2), and by both production and the tests. It
-- must therefore only use SQL which is understood by all of them:
--   * Identity columns are declared with the SQL standard syntax
--     "GENERATED BY DEFAULT AS IDENTITY", not SERIAL or AUTO_INCREMENT.
--   * No vendor specific procedural code, e.g. PL/pgSQL "DO" blocks. The
--     script is only run against an empty database, which is controlled by
--     the caller.
--   * No expression indexes, e.g. on lower(name), as H2 does not support
--     them. Name lookups are case-insensitive via the queries instead.
--   * TEXT and BYTEA are supported by both databases.
--
-- And it keeps to what other databases know as well, where that costs
-- nothing, so less differs when one of them is to be supported:
--   * "NOT NULL" on the column, not a CHECK constraint.
--   * "DEFAULT CURRENT_TIMESTAMP", not now().
--   * No BOOLEAN: a flag is an INTEGER, 0 or 1.
--   * No large value in one row: the content of a Data Object is stored in
--     parts (eds_data_parts), so nothing is read with substring() or
--     measured with octet_length(), which differ between databases.
--
-- Every foreign key has an index which starts with its column: the primary
-- key, a unique constraint, or a "CREATE INDEX" after the table. H2 creates
-- one for a foreign key by itself, PostgreSQL doesn't. Without it, each row
-- which a delete cascades to is looked for by reading the whole table: the
-- deletion of a Circle with 19,441 Objects took 205 seconds instead of 2 in
-- the load test of 2026-11-20. SchemaIndexTest checks the rule.
--
-- This file is the source of truth. The build copies it to
-- accessories/release/postgresql/, so do not edit that copy.
--
-- This script contain the following tables:
--  * System Specific tables
--     o eds_version    -  Simple Version information, to correlate EDS & DB version
--     o eds_settings   -  Settings for this instance of EDS
--  * Accounts & Relations for access control
--     o eds_masterkey  -  Version and key check value of the MasterKey
--     o eds_members    -  Members who may access EDS
--     o eds_circles    -  Circles of Trust that members may use for sharing data
--     o eds_keys       -  Symmetric Keys, used by Circles for sharing data
--     o eds_trustees   -  Relation information for each Member & Circle
--  * Folders & Shared (encrypted) data
--     o eds_types      -  The type of Objects (Data) to be stored
--     o eds_metadata   -  Objects to be stored, related to datatype & Circles
--     o eds_data       -  What is stored for each Object: its key and checksum
--     o eds_data_parts -  The actual encrypted data of each Object, in parts
-- =============================================================================

-- =============================================================================
-- The Version table is used to correlate the information about the current
-- database version with the EDS version. If not matching, then EDS will not
-- work correctly.
--   The table also serves a simple purpose of acting as a break for attempts at
-- accidentally trying to upgrade the EDS to an invalid version.
--   The API request for "version" will also return the latest information from
-- this table.
-- =============================================================================
CREATE TABLE eds_versions (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
  schema_version   INTEGER NOT NULL,
  eds_version      VARCHAR(10) NOT NULL,
  installed        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT version_pk                     PRIMARY KEY (id),

  /* Unique Constraints */
  CONSTRAINT version_unique_version         UNIQUE (schema_version, eds_version)
);
-- EDS 2.0 is a clean break from earlier versions, which cannot be upgraded in
-- place. Hence, only the current schema version is registered. It must match
-- StartupBean.DB_VERSION. It stays 4 while EDS 2.0 is being made, however
-- the tables change, and is first raised by a change after 2.0 is released.
INSERT INTO eds_versions(schema_version, eds_version) VALUES (4, '2.0.0');

-- =============================================================================
-- The EDS is configured via a set of property values, which are all stored in
-- the database. This is done so the same cluster of stateless EDS instances
-- will share the same settings.
--   The Settings consist of a series of key-value pairs, though to avoid any
-- potential conflicts with the word "key" that is also used throughout the
-- system to mean "Cryptography Key" - they are instead referred to as
-- name-setting pairs.
--   The Settings are managed via a System Administrator API request, which will
-- only be used as part of the setup. Certain values cannot be altered after the
-- initial setup. However, which values and why are described in the installation
-- documentation.
-- =============================================================================
CREATE TABLE eds_settings (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
  name             VARCHAR(256) NOT NULL,
  setting          VARCHAR(256),
  altered          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  added            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT setting_pk                     PRIMARY KEY (id),

  /* Unique Constraints */
  CONSTRAINT setting_unique_name            UNIQUE (name)
);

-- =============================================================================
-- This is the Account table for all Members. By default, it is empty, and the
-- first record to be added will be the System Administrator, under the name
-- which whoever comes first gives: no name is set for it.
--   The Account has a credential, which must be a unique (lower case)
-- identifier for the Account Holder or Member. The Account also holds a
-- System-generated Public/Private Key pair, where the Public Key is stored
-- directly, but the Private Key is stored encrypted using a temporary Symmetric
-- Key that is derived from the request.
--   To Authenticate the Member, the temporary Symmetric Key is used to decrypt
-- the Private Key, and if it can successfully unlock a secret encrypted with
-- the Public Key, then it matches. If not, then the System will Warn the
-- Member that the Account was used incorrectly.
--   The System Administrator is the first Member Account added, and upon
-- creating it, the provided secret (Passphrase or Private Key) is then used
-- to derive a Symmetric Key to encrypt the Private Key. This way, there is
-- neither a default name nor a default secret for the System Administrator,
-- which someone could have left as it was. It stays the System Administrator
-- by being the first, the one with the lowest Id, whatever its name becomes.
--   Note, that the first version of the EDS is not holding any mechanisms to
-- prevent Authentication Attacks. This is a deliberate design decision as the
-- EDS is only supposed to be a Data Storage Facility, and this be further down
-- the entire Application Layer.
--   The Member Role is giving a pointer towards what kinds of permissions that
-- a member has, it can be either admin, standard, session or guest.
--   Sessions are important for websites, where a user is logging in and then
-- just works with a session onwards. To better integrate EDS into websites, it
-- is important EDS also supports Sessions. This is done by having 3 fields in
-- this table, the session_checksum, which is generated using the MasterKey and
-- used to find the member account. Secondly, the member's private key is
-- encrypted using both a PBKDF2 symmetric key and the MasterKey. And finally,
-- the expiry flag, which is pre-calculated with the "login time" and the maximum
-- lifetime of a session. So a Timed service can stop any existing sessions that
-- have not been logged out.
-- =============================================================================
-- =============================================================================
-- The MasterKey table holds the version and key check value (KCV) of each
-- MasterKey, never the key or its source. The highest version is the current
-- MasterKey; a wrong MasterKey is detected by comparing the KCV.
-- =============================================================================
CREATE TABLE eds_masterkey (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
  version          INTEGER NOT NULL,
  kcv              VARCHAR(256) NOT NULL,
  altered          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  added            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT masterkey_pk                   PRIMARY KEY (id),

  /* Unique Constraints */
  CONSTRAINT masterkey_unique_version       UNIQUE (version)
);

CREATE TABLE eds_members (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
  external_id      VARCHAR(36) NOT NULL,
  name             VARCHAR(75) NOT NULL,    -- Member Authentication information
  salt             VARCHAR(256) NOT NULL,
  pbe_algorithm    VARCHAR(25) DEFAULT 'PBE_GCM_256' NOT NULL,
  pbe_iterations   INTEGER NOT NULL,        -- PBKDF2 iterations of the current passphrase
  key_algorithm    VARCHAR(25) DEFAULT 'MLKEM1024_P384' NOT NULL,
  external_key     TEXT,           -- External Public Key, with unknown length
  public_key       VARCHAR(4096) NOT NULL,  -- Public Keys (ML-KEM-1024 + P-384), stored armored
  private_key      VARCHAR(16384) NOT NULL, -- Private Keys, double wrapped (password key, MasterKey)
  member_role      VARCHAR(10) DEFAULT 'STANDARD' NOT NULL,
  avatar           VARCHAR(32),    -- ID of a picture the clients know, e.g. 'raven'
  settings         VARCHAR(4096),  -- The Member's own settings for clients, a JSON object
  external_vault   TEXT,           -- The Member's vault, text of a client (E2E.md), as given
  invitation_expire TIMESTAMP,     -- Time, when a pending Invitation expires
  failed_logins    INTEGER DEFAULT 0 NOT NULL, -- Failed passphrase attempts in the current window (#68)
  first_failed_at  TIMESTAMP,      -- Start of the current failed-attempt window (#68)
  locked_until     TIMESTAMP,      -- The account is locked until this time, after too many failures (#68)
  altered          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  added            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT member_pk                      PRIMARY KEY (id),

  /* Unique Constraints */
  CONSTRAINT member_unique_external_id      UNIQUE (external_id),
  CONSTRAINT member_unique_name             UNIQUE (name),
  CONSTRAINT member_unique_salt             UNIQUE (salt)
);

-- =============================================================================
-- A Member may have several Sessions, one per login (PLAN.md, Crypto §2a and
-- "Several sessions"): the checksum, which is generated using the MasterKey and
-- used to find the Session, the Member's private keys, encrypted using both a
-- key from the Session token and the MasterKey, and the expiry, which is
-- pre-calculated with the "login time" and the maximum lifetime of a Session.
-- A Session goes with its Member.
-- =============================================================================
CREATE TABLE eds_sessions (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
  member_id        INTEGER NOT NULL,
  checksum         VARCHAR(256) NOT NULL,   -- MasterKey Checksum of the Session token
  crypto           VARCHAR(16384) NOT NULL, -- Private Keys, double wrapped (session key, MasterKey)
  expire           TIMESTAMP NOT NULL,      -- Time, when the Session expires
  altered          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  added            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT session_pk                     PRIMARY KEY (id),
  CONSTRAINT session_member_fk              FOREIGN KEY (member_id) REFERENCES eds_members (id) ON DELETE CASCADE,

  /* Unique Constraints */
  CONSTRAINT session_unique_checksum        UNIQUE (checksum)
);
CREATE INDEX session_member_idx ON eds_sessions (member_id);

-- =============================================================================
-- Circles act as groupings for a collection of Members sharing data. A Circle
-- is thus having an identifying name and nothing else really.
--   Circles can be created by either the System Administrator or a Member with
-- Circle Administrative privileges. When creating a new Circle, the initial new
-- Circle Administrator must be added, which cannot be the System Administrator.
--   When the Circle Secret is to be rotated next (PLAN.md, Crypto C6) is kept
-- with the Circle: a new Circle and the end of a rotation set it a period
-- (eds.circle.secret.rotation.days) ahead, a Trustee who leaves or is removed
-- sets it to now. Once it has passed, the rotation starts at the next request
-- of a Trustee which unwraps the Circle Secret. Null: not due at all.
-- =============================================================================
CREATE TABLE eds_circles (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
  external_id      VARCHAR(36) NOT NULL,
  name             VARCHAR(75) NOT NULL,
  avatar           VARCHAR(32),    -- ID of a picture the clients know, e.g. 'longship'
  external_key     BYTEA,          -- External Circle Key, with unknown length
  rotate_circle_key_due TIMESTAMP, -- When the Circle Secret is to be rotated next
  altered          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  added            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT circle_pk                      PRIMARY KEY (id),

  /* Unique Constraints */
  CONSTRAINT circle_unique_external_id      UNIQUE (external_id),
  CONSTRAINT circle_unique_name             UNIQUE (name)
);
CREATE INDEX circle_rotate_due_idx ON eds_circles (rotate_circle_key_due);

-- =============================================================================
-- The stored bytes of a Circle: the sum of part_length of the parts of its
-- objects, so the storage ceiling is checked against a row for each Circle
-- instead of every part (PLAN.md, Streaming, "The storage ceiling"). They
-- change in the same transaction as the parts, by one statement which adds to
-- them. They have a table of their own, not a column of eds_circles: a write
-- holds this row until it commits, while the delete of a Circle locks the
-- Circle's row before the rows of its content, so the two never wait for each
-- other in a circle. The row is made with the Circle, and goes with it.
-- =============================================================================
CREATE TABLE eds_circle_storage (
  circle_id        INTEGER NOT NULL,
  stored_bytes     BIGINT DEFAULT 0 NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT circle_storage_pk              PRIMARY KEY (circle_id),
  CONSTRAINT circle_storage_circle_fk       FOREIGN KEY (circle_id) REFERENCES eds_circles (id) ON DELETE CASCADE
);

-- =============================================================================
-- A central part of the EDS is encryption. All data is encrypted using a series
-- of Symmetric Encryption Keys. All saved Symmetric Keys are stored encrypted.
-- However, it is still important to have certain meta-data available.
--   To generate a new Key, it is important to know which algorithm and length
-- to use. By default, all allowed Algorithms & key lengths are limited to what
-- is provided by the Java Runtime Environment.
-- Initially EDS used the AES Block encryption, CBC, which is no longer
-- considered safe to use. Hence as of EDS 2.0, the default is GCM, at the max
-- size supported by the Java Runtime Environment, i.e., 256 bits.
--   A row is a Circle Secret of a Circle; the secret itself is only kept
-- wrapped, with the Trustees. A Circle has one ACTIVE secret, and while its
-- secret is rotated (PLAN.md, Crypto C6) also the RETIRING one, which the
-- objects not yet re-encrypted are still on. The row of a retired secret is
-- deleted when no object is left on it.
-- =============================================================================
CREATE TABLE eds_keys (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
  circle_id        INTEGER NOT NULL,
  algorithm        VARCHAR(256) DEFAULT 'AES_GCM_256' NOT NULL,
  status           VARCHAR(256) DEFAULT 'ACTIVE' NOT NULL,
  altered          TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,
  added            TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT key_pk                         PRIMARY KEY (id),
  CONSTRAINT key_circle_fk                  FOREIGN KEY (circle_id) REFERENCES eds_circles (id) ON DELETE CASCADE
);
CREATE INDEX key_circle_idx ON eds_keys (circle_id);

-- =============================================================================
-- The Trustee is the relation between Member Accounts and Circles. The Key
-- which belongs to a Circle is stored with this relation encrypted with the
-- Member's Public Key.
--   A Member is also having a Trust Level, which determines what the Member may
-- or may not do within a Circle:
--     * Guest
--         This is the lowest level. A Guest may view the meta-information from a
--       Circle, which includes Members, Folders & Object Meta information.
--       However, Guests do not have a copy of the Circle Key available, meaning
--       that they cannot read the data belonging to a Circle.
--     * Read
--         With this level of access, the Member may do what the Guest can do,
--       but contrary to a Guest, they do have access to the Circle Key, and may
--       therefore also read all the Objects belonging to a Circle
--     * Write
--         With this level of access, the Member may do all that Members with
--       Read rights may do, and additionally, they may also create, update and
--       delete Folders and Objects belonging to the Circle.
--         Members with Write access may also initiate a Key migration process,
--       meaning that if a Key has expired, they may issue a new Key and start
--       re-encrypting all content.
--     * Administrator
--         Administrators have the highest trust level, meaning that they may do
--       all with the Circle that Members with lower level of access may. They
--       may also manage the Circle itself, meaning adding or revoking Members'
--       access to the Circle and changing the Trust Level of a Member.
--   A Member can only belong to a Circle with Access to the Key. the actual Key
-- is stored with the relation and not within the Key table. For Guests, the Key
-- stored is simply "Not Applicable".
--   While the Circle Secret is rotated (PLAN.md, Crypto C6), the row also
-- holds the retiring secret, wrapped as before, so the objects which are not
-- yet re-encrypted can be read: previous_key_id and previous_circle_key.
-- =============================================================================
CREATE TABLE eds_trustees (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
  member_id        INTEGER NOT NULL,
  circle_id        INTEGER NOT NULL,
  key_id           INTEGER NOT NULL,
  trust_level      VARCHAR(10) NOT NULL,
  circle_key       VARCHAR(8192) DEFAULT 'Not Applicable' NOT NULL,
  external_key     BYTEA,          -- The Member's secret in the Circle, text of a client (E2E.md), sealed
  previous_key_id  INTEGER,        -- The retiring Circle Secret, while it is rotated
  previous_circle_key VARCHAR(8192),
  altered          TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  added            TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT trustee_pk                     PRIMARY KEY (id),
  CONSTRAINT trustee_member_fk              FOREIGN KEY (member_id) REFERENCES eds_members (id) ON DELETE CASCADE,
  CONSTRAINT trustee_circle_fk              FOREIGN KEY (circle_id) REFERENCES eds_circles (id) ON DELETE CASCADE,
  CONSTRAINT trustee_key_fk                 FOREIGN KEY (key_id) REFERENCES eds_keys (id),
  CONSTRAINT trustee_previous_key_fk        FOREIGN KEY (previous_key_id) REFERENCES eds_keys (id),

  /* Unique Constraints */
  CONSTRAINT trustee_unique_fks             UNIQUE (member_id, circle_id, key_id)
);
CREATE INDEX trustee_circle_idx ON eds_trustees (circle_id);
CREATE INDEX trustee_key_idx ON eds_trustees (key_id);
CREATE INDEX trustee_previous_key_idx ON eds_trustees (previous_key_id);

-- =============================================================================
-- The room access of a pending invitation (PLAN.md, Crypto, Invitations). An
-- administrator of a Circle invites a new Member into it: the Circle Secret is
-- sealed with a key derived from the invitation token (HKDF), and outside
-- with the MasterKey, so neither the database nor the MasterKey alone opens
-- it. When the invitation is accepted, the Trustee is created and the row is
-- deleted; it goes with the invited Member or the Circle.
-- =============================================================================
CREATE TABLE eds_invitations (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
  member_id        INTEGER NOT NULL,
  circle_id        INTEGER NOT NULL,
  key_id           INTEGER NOT NULL,
  trust_level      VARCHAR(10) NOT NULL,
  circle_key       VARCHAR(8192) NOT NULL,
  external_key     BYTEA,          -- The invited Member's secret in the Circle (E2E.md), sealed
  altered          TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  added            TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT invitation_pk                  PRIMARY KEY (id),
  CONSTRAINT invitation_member_fk           FOREIGN KEY (member_id) REFERENCES eds_members (id) ON DELETE CASCADE,
  CONSTRAINT invitation_circle_fk           FOREIGN KEY (circle_id) REFERENCES eds_circles (id) ON DELETE CASCADE,
  CONSTRAINT invitation_key_fk              FOREIGN KEY (key_id) REFERENCES eds_keys (id) ON DELETE CASCADE
);
CREATE INDEX invitation_member_idx ON eds_invitations (member_id);
CREATE INDEX invitation_circle_idx ON eds_invitations (circle_id);
CREATE INDEX invitation_key_idx ON eds_invitations (key_id);

-- =============================================================================
-- Data stored is completely unknown to the EDS, since multiple Clients may
-- access the system, it cannot be guaranteed that they all know what the
-- Objects may be. To avoid this problem and to ensure that there is a simple
-- way to map Objects over, they must be stored with a type. All known types are
-- stored in this table.
--   The types are stored as a map. Where the keys (names) must be unique, and
-- the values can be anything. By default, one record exists, which is a folder.
-- The folder type is used primarily internally to help structure the Objects
-- better.
-- =============================================================================
CREATE TABLE eds_datatypes (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
  datatype_name    VARCHAR(75) NOT NULL,
  datatype_value   VARCHAR(256) NOT NULL,
  altered          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  added            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT datatype_pk                    PRIMARY KEY (id),

  /* Unique Constraints */
  CONSTRAINT datatype_unique_name           UNIQUE (datatype_name)
);

-- The standard Object Types: folders, plain Data Objects, thumbnails, whose
-- parent is the Data Object they show, and the entries of features, such as
-- the messages of the chat, which are kept in the feature's hidden folder
-- (FEATURES.md). The rest is left to the initial setup to create
INSERT INTO eds_datatypes (datatype_name, datatype_value) VALUES
    ('folder', 'Folder'),
    ('data', 'Data Object'),
    ('thumbnail', 'Thumbnail'),
    ('entry', 'Entry of a Feature');

-- =============================================================================
-- The main objective of EDS is to store data securely. This table contains the
-- primary metadata for each Object stored, but not the data for the Object.
-- This data is stored in the data table. It was done so, for two reasons, first
-- as not all Objects may have data associated, and secondly, to avoid references
-- to Null data, as it usually indicates flaws in the model.
--   Objects are stored with an external Id, which is exposed via the API, the
-- internal Id is not exposed but is kept for internal referencing.
-- All Objects are also stored with a type. EDS has two default types, the most
-- important is "Folder", which allows Members to structure their data, and the
-- second is simply "data", if the system using EDS has enough information to
-- control the Data Objects.
--   Folders are also Objects referencing the default 'Folder' type. It is
-- possible to create subfolders and add data to any Folder belonging to the
-- Circle in question. As it is possible to create Sub-folders, the structure
-- is recursive: the parent Id references the parent Folder (or, for a
-- thumbnail, the Data Object it shows).
--   Loops can't occur, as Folders can't be moved: a Folder keeps the parent
-- it was created in, and only Data Objects (files) change their folder. The
-- earlier check "parent_id < id" enforced this in the database as well, but
-- it also refused moving a file into a Folder created after the file; it was
-- dropped in November 2026.
-- =============================================================================
CREATE TABLE eds_metadata (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
  external_id      VARCHAR(36) NOT NULL,
  parent_id        INTEGER,
  circle_id        INTEGER NOT NULL,
  datatype_id      INTEGER NOT NULL,
  name             VARCHAR(512),
  name_key         VARCHAR(128),   -- Keyed hash of the name from a client of a chamber, as the name is ciphertext, see E2E.md
  media_type       VARCHAR(255),   -- Media type for serving the content, see PLAN.md, Streaming
  altered          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  added            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT metadata_pk                    PRIMARY KEY (id),
  CONSTRAINT metadata_circle_fk             FOREIGN KEY (circle_id) REFERENCES eds_circles (id) ON DELETE CASCADE,
  CONSTRAINT metadata_datatype_fk           FOREIGN KEY (datatype_id) REFERENCES eds_datatypes (id),

  /* Unique Constraints */
  CONSTRAINT metadata_unique_external_id    UNIQUE (external_id),
  -- A name is unique within its folder. In a chamber the name is ciphertext,
  -- different each time, so the Name Key is what is unique. NULL where no
  -- Name Key was sent; PostgreSQL and H2 allow any number of NULLs here.
  CONSTRAINT metadata_unique_name_key       UNIQUE (parent_id, name_key)
);
CREATE INDEX metadata_circle_idx ON eds_metadata (circle_id);
CREATE INDEX metadata_datatype_idx ON eds_metadata (datatype_id);

-- =============================================================================
-- Metadata with data associated have the data & key information stored in this
-- table, with a reference to the Metadata record. Objects which do not have any
-- data associated will also not have a record present here.
--   All data stored here is stored encrypted. If the Key has expired, then the
-- Data is considered deprecated, and it is pending deletion and can no longer
-- be used.
-- =============================================================================
CREATE TABLE eds_data (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
  metadata_id      INTEGER NOT NULL,
  key_id           INTEGER NOT NULL,
  checksum         VARCHAR(256) NOT NULL,
  sanity_status    VARCHAR(256) DEFAULT 'Ok' NOT NULL,
  sanity_checked   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  altered          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  added            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT data_pk                        PRIMARY KEY (id),
  CONSTRAINT data_metadata_fk               FOREIGN KEY (metadata_id) REFERENCES eds_metadata (id) ON DELETE CASCADE,
  CONSTRAINT data_key_fk                    FOREIGN KEY (key_id) REFERENCES eds_keys (id)
);
CREATE INDEX data_metadata_idx ON eds_data (metadata_id);
-- With the ID, the rotation takes the next content of a key in the order of
-- the IDs from the index alone; on the key only, PostgreSQL read the content
-- in ID order and left out the other keys (the load run of 2026-11-23).
CREATE INDEX data_key_idx ON eds_data (key_id, id);
-- =============================================================================
-- The encrypted data of a Data Object, as a row for each part of it. A part is
-- a range of the bytes, nothing more: where one part ends and the next starts
-- says nothing about the content, and the database knows as little about it
-- as before (PLAN.md, Streaming). The first part is short, so the start of
-- the data (its header) is read without the rest; the others have the size
-- which was set when they were written (eds.stream.read.batch.size).
--   Each part tells where it starts and how long it is, so a range is read by
-- these two alone, and the size of the parts may change without anything
-- stored having to be written anew. The length of the data is the sum of the
-- lengths of its parts. Data without content has no parts.
-- =============================================================================
CREATE TABLE eds_data_parts (
  data_id          INTEGER NOT NULL,
  part_offset      BIGINT NOT NULL,   -- Where the part starts in the data, from 0
  part_length      INTEGER NOT NULL,  -- The number of bytes in the part
  part             BYTEA NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT data_part_pk                   PRIMARY KEY (data_id, part_offset),
  CONSTRAINT data_part_data_fk              FOREIGN KEY (data_id) REFERENCES eds_data (id) ON DELETE CASCADE
);


-- =============================================================================
-- Features (FEATURES.md). A feature is something a Circle can have beside its files:
-- the chat, a calendar. The stone doesn't know what a feature is for. It keeps a
-- declaration, which names the feature, the kinds of its entries and the rules
-- for them, and it stores and guards the entries accordingly.
--   The System Administrator decides which features the stone offers.
-- =============================================================================
CREATE TABLE eds_features (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
  name             VARCHAR(32) NOT NULL,
  version          INTEGER NOT NULL,
  declaration      TEXT NOT NULL,           -- A JSON object, as the System Administrator gave it
  altered          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  added            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT feature_pk                        PRIMARY KEY (id),

  /* Unique Constraints */
  CONSTRAINT feature_unique_name               UNIQUE (name)
);

-- =============================================================================
-- A feature in a Circle, switched on by an administrator of the Circle. Its
-- entries are kept in a folder of the Circle's root folder, named with a dot
-- and the feature's name. Switched off, the entries stay and are hidden.
-- =============================================================================
CREATE TABLE eds_circle_features (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
  circle_id        INTEGER NOT NULL,
  feature_id          INTEGER NOT NULL,
  state            VARCHAR(10) DEFAULT 'ON' NOT NULL,
  folder_id        INTEGER NOT NULL,        -- The folder (eds_metadata) with the entries
  next_position    BIGINT DEFAULT 1 NOT NULL,
  altered          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  added            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT circle_feature_pk                 PRIMARY KEY (id),
  CONSTRAINT circle_feature_circle_fk          FOREIGN KEY (circle_id) REFERENCES eds_circles (id) ON DELETE CASCADE,
  CONSTRAINT circle_feature_feature_fk            FOREIGN KEY (feature_id) REFERENCES eds_features (id),

  /* Unique Constraints */
  CONSTRAINT circle_feature_unique             UNIQUE (circle_id, feature_id)
);
CREATE INDEX circle_feature_feature_idx ON eds_circle_features (feature_id);

-- =============================================================================
-- What the stone notes about an entry of a feature. The content is a Data Object
-- like any other, of the type 'entry', encrypted with the Circle Secret. The
-- author is sealed with a subkey of the Circle Secret, and the owner tag is a
-- keyed value of it, so the database doesn't show who wrote what.
-- =============================================================================
CREATE TABLE eds_entries (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
  metadata_id      INTEGER NOT NULL,
  circle_feature_id   INTEGER NOT NULL,
  kind             VARCHAR(32) NOT NULL,
  position         BIGINT NOT NULL,
  about_id         INTEGER,        -- The entry (eds_entries) this one is about
  owner_tag        VARCHAR(64) NOT NULL,
  author           BYTEA NOT NULL,
  closed           INTEGER DEFAULT 0 NOT NULL,  -- 1 if the entry is closed; not every database has BOOLEAN
  changed          TIMESTAMP,
  altered          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  added            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT entry_pk                       PRIMARY KEY (id),
  CONSTRAINT entry_metadata_fk              FOREIGN KEY (metadata_id) REFERENCES eds_metadata (id) ON DELETE CASCADE,
  CONSTRAINT entry_circle_feature_fk           FOREIGN KEY (circle_feature_id) REFERENCES eds_circle_features (id) ON DELETE CASCADE,

  /* Unique Constraints */
  CONSTRAINT entry_unique_metadata          UNIQUE (metadata_id),
  CONSTRAINT entry_unique_position          UNIQUE (circle_feature_id, position)
);
-- The entries about an entry (reactions, replies), and the entries of a kind
-- in a feature: without them, PostgreSQL read the whole table, or every entry
-- of the feature (the load run of 2026-11-23).
CREATE INDEX entry_about_idx ON eds_entries (about_id);
CREATE INDEX entry_kind_idx ON eds_entries (circle_feature_id, kind, position);

-- =============================================================================
-- Status keys (STATUS.md). A key reads the status of the stone, its load and
-- inventory in general numbers, and nothing else, so someone who looks after
-- several stones needn't log in to each. Only the SHA-512 hash of a key is
-- kept. It is a plain hash, not one of the MasterKey: the status is answered
-- while the stone is locked.
-- =============================================================================
CREATE TABLE eds_status_keys (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
  label            VARCHAR(75) NOT NULL,
  checksum         VARCHAR(128) NOT NULL,
  altered          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  added            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

  /* Primary & Foreign Keys */
  CONSTRAINT status_key_pk                  PRIMARY KEY (id),

  /* Unique Constraints */
  CONSTRAINT status_key_unique_label        UNIQUE (label),
  CONSTRAINT status_key_unique_checksum     UNIQUE (checksum)
);
